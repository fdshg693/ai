/**
 * Site-local publication overrides, layered on top of the ai-tools.yaml
 * derived SOURCE_REGISTRY (see source-registry.mjs).
 *
 * ai-tools.yaml is the SSOT for which tool/plugin exists and what ships in
 * the marketplace/skill-catalog outputs. Some registered plugins or skills
 * should still ship there but must NOT appear on this public site (e.g. an
 * internal-facing skill that is fine to install via the marketplace but
 * isn't meant to be advertised publicly). This file is where that site-only
 * exclusion is declared, without touching ai-tools.yaml or the registry.
 *
 * The reverse case (publishing something on the site that isn't registered
 * in ai-tools.yaml) is intentionally unsupported: this file can only hide
 * registered entries, never add new ones.
 *
 * Do not edit this file's SITE_OVERRIDES value by hand — edit
 * site-overrides.yaml instead.
 */

import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
import yaml from "js-yaml";

const SCRIPT_DIRECTORY = path.dirname(fileURLToPath(import.meta.url));
const SITE_ROOT = path.resolve(SCRIPT_DIRECTORY, "..");
const OVERRIDES_PATH = path.join(SITE_ROOT, "site-overrides.yaml");

function loadOverrides(overridesPath = OVERRIDES_PATH) {
  if (!fs.existsSync(overridesPath)) return { excludeSources: [], excludeSkills: [] };
  const data = yaml.load(fs.readFileSync(overridesPath, "utf8")) ?? {};
  const exclude = data.exclude ?? {};
  return {
    excludeSources: exclude.sources ?? [],
    excludeSkills: exclude.skills ?? [],
  };
}

export const SITE_OVERRIDES = loadOverrides();
