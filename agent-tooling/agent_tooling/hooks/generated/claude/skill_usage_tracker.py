ENQUETE_STATE_SUBDIR = ("state", "skill_usage")


def state_path(hooks_dir, session_id):
    return Path(hooks_dir).joinpath(*ENQUETE_STATE_SUBDIR, f"{session_id}.json")


def load_state(path):
    try:
        data = json.loads(path.read_text(encoding="utf-8"))
    except (OSError, ValueError):
        return {"skills": {}, "stop_attempts": 0}
    if not isinstance(data, dict):
        return {"skills": {}, "stop_attempts": 0}
    skills = data.get("skills")
    if not isinstance(skills, dict):
        skills = {}
    stop_attempts = data.get("stop_attempts")
    if not isinstance(stop_attempts, int):
        stop_attempts = 0
    return {"skills": skills, "stop_attempts": stop_attempts}


def save_state(path, state):
    path.parent.mkdir(parents=True, exist_ok=True)
    tmp = path.with_name(path.name + ".tmp")
    tmp.write_text(json.dumps(state, ensure_ascii=False, indent=2), encoding="utf-8")
    tmp.replace(path)


# --- inlined from adapters/claude/common/skill_frontmatter.py ---
def read_frontmatter(skill_md_path):
    try:
        text = skill_md_path.read_text(encoding="utf-8")
    except OSError:
        return None
    if not text.startswith("---"):
        return None
    end = text.find("\n---", 3)
    if end == -1:
        return None
    try:
        data = yaml.safe_load(text[3:end])
    except yaml.YAMLError:
        return None
    if not isinstance(data, dict):
        return None
    return data


def find_skill_dir_by_name(name, roots):
    """Search `roots` (iterable of Path) recursively for a SKILL.md whose
    frontmatter `name` matches `name` (case-insensitive).

    Falls back to a directory whose basename matches, if no frontmatter-name
    match is found anywhere across the roots. Scans all roots fully before
    falling back, so a real name match anywhere always wins over a
    directory-name coincidence.
    """
    name_lower = name.strip().lower()
    fallback = None
    for root in roots:
        if not root.is_dir():
            continue
        for skill_md in sorted(root.rglob("SKILL.md")):
            frontmatter = read_frontmatter(skill_md)
            if frontmatter is None:
                continue
            fm_name = frontmatter.get("name")
            if isinstance(fm_name, str) and fm_name.strip().lower() == name_lower:
                return skill_md.parent
            if fallback is None and skill_md.parent.name.lower() == name_lower:
                fallback = skill_md.parent
    return fallback


