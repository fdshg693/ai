def _is_docstring(node: ast.stmt) -> bool:
    return (
        isinstance(node, ast.Expr)
        and isinstance(node.value, ast.Constant)
        and isinstance(node.value.value, str)
    )


def _slice(source: str, node: ast.AST) -> str:
    return ast.get_source_segment(source, node) or ""


def _resolve_under_package(path: Path, package_root: Path) -> Path:
    resolved = path.resolve()
    try:
        rel = resolved.relative_to(package_root.resolve())
    except ValueError as exc:
        raise InlineError(f"import resolves outside agent_tooling/: {resolved}") from exc
    if rel.parts[:1] == ("hooks",) and len(rel.parts) > 1 and rel.parts[1] in NOT_INLINABLE:
        raise InlineError(f"cannot inline {rel.as_posix()} from {resolved}")
    return resolved


def _module_file(base: Path, package_root: Path) -> Path:
    if base.is_dir() and (base / "__init__.py").is_file():
        return _resolve_under_package(base / "__init__.py", package_root)
    py = base if base.suffix == ".py" else base.with_suffix(".py")
    if py.is_file():
        return _resolve_under_package(py, package_root)
    init = base / "__init__.py"
    if init.is_file():
        return _resolve_under_package(init, package_root)
    raise InlineError(f"cannot resolve module file: {base}")


def resolve_relative(
    current_file: Path, module: str | None, level: int, package_root: Path
) -> Path:
    if level < 1:
        raise InlineError(f"{current_file}: expected relative import, got level={level}")
    base = current_file.parent
    for _ in range(level - 1):
        base = base.parent
    if module:
        for part in module.split("."):
            base = base / part
    return _module_file(base, package_root)


def resolve_absolute_package(module: str, package_root: Path) -> Path:
    parts = module.split(".")
    if parts[0] != "agent_tooling":
        raise InlineError(f"absolute import is not agent_tooling.*: {module}")
    base = package_root
    for part in parts[1:]:
        base = base / part
    return _module_file(base, package_root)


def hook_targets(
    node: ast.stmt,
    current_file: Path,
    package_root: Path,
    allowed: frozenset[str] = frozenset(),
) -> list[Path]:
    """Package modules to inline for one top-level import; ``allowed`` names stay imports."""
    if isinstance(node, ast.Import):
        targets = []
        for alias in node.names:
            top = alias.name.split(".")[0]
            if top == "agent_tooling":
                targets.append(resolve_absolute_package(alias.name, package_root))
            elif top not in STDLIB and top not in allowed:
                raise InlineError(f"{current_file}: import {alias.name} is outside agent_tooling/")
        return targets
    if not isinstance(node, ast.ImportFrom):
        return []
    if node.level and node.level > 0:
        if node.module:
            return [resolve_relative(current_file, node.module, node.level, package_root)]
        return [
            resolve_relative(current_file, alias.name, node.level, package_root)
            for alias in node.names
        ]
    module = node.module or ""
    top = module.split(".")[0] if module else ""
    if top == "agent_tooling":
        return [resolve_absolute_package(module, package_root)]
    if top in STDLIB or module in STDLIB or top in allowed:
        return []
    raise InlineError(f"{current_file}: from {module} import ... is outside agent_tooling/")


def _is_future(node: ast.stmt) -> bool:
    return isinstance(node, ast.ImportFrom) and node.module == "__future__" and node.level == 0


def _import_tops(node: ast.stmt) -> list[str]:
    if isinstance(node, ast.Import):
        return [alias.name.split(".")[0] for alias in node.names]
    if isinstance(node, ast.ImportFrom) and not node.level:
        return [(node.module or "").split(".")[0]]
    return []


def _is_stdlib_import(node: ast.stmt) -> bool:
    if _is_future(node):
        return True
    tops = _import_tops(node)
    return bool(tops) and all(top in STDLIB for top in tops)


def _is_third_party_import(node: ast.stmt, allowed: frozenset[str]) -> bool:
    tops = _import_tops(node)
    return bool(tops) and all(top in allowed or top in STDLIB for top in tops)


def _is_main_guard(node: ast.stmt) -> bool:
    if not isinstance(node, ast.If) or not isinstance(node.test, ast.Compare):
        return False
    test = node.test
    operands = [test.left, *test.comparators]
    return (
        len(test.ops) == 1
        and isinstance(test.ops[0], ast.Eq)
        and any(isinstance(o, ast.Name) and o.id == "__name__" for o in operands)
        and any(isinstance(o, ast.Constant) and o.value == "__main__" for o in operands)
    )


def _skip_ranges(
    tree: ast.Module, *, skip_docstring: bool, skip_main_guard: bool = False
) -> list[tuple[int, int]]:
    ranges: list[tuple[int, int]] = []
    body = list(tree.body)
    if skip_docstring and body and _is_docstring(body[0]):
        ranges.append((body[0].lineno, body[0].end_lineno or body[0].lineno))
        body = body[1:]
    for node in body:
        if isinstance(node, (ast.Import, ast.ImportFrom)) or (
            skip_main_guard and _is_main_guard(node)
        ):
            ranges.append((node.lineno, node.end_lineno or node.lineno))
    return ranges


def _line_is_skipped(n: int, ranges: list[tuple[int, int]]) -> bool:
    return any(a <= n <= b for a, b in ranges)


def remaining_source(
    source: str,
    tree: ast.Module,
    *,
    skip_docstring: bool,
    skip_main_guard: bool = False,
    skip_lines: tuple[int, int] | None = None,
) -> str:
    ranges = _skip_ranges(tree, skip_docstring=skip_docstring, skip_main_guard=skip_main_guard)
    if skip_lines:
        ranges.append(skip_lines)
    lines = source.splitlines(True)
    kept: list[str] = []
    for i, line in enumerate(lines, 1):
        if i == 1 and line.startswith("#!"):
            continue
        if _line_is_skipped(i, ranges):
            continue
        kept.append(line)
    text = "".join(kept).strip("\n")
    return (text + "\n") if text else ""


def module_docstring_source(source: str, tree: ast.Module) -> str:
    if tree.body and _is_docstring(tree.body[0]):
        raw = _slice(source, tree.body[0])
        if raw:
            return raw if raw.endswith("\n") else raw + "\n"
    return '"""Generated hook script."""\n'


def _import_name(dependency: str) -> str:
    match = re.match(r"[A-Za-z0-9][A-Za-z0-9._-]*", dependency.strip())
    if not match:
        raise InlineError(f"invalid PEP 723 dependency: {dependency!r}")
    name = re.sub(r"[-_.]+", "-", match.group(0)).lower()
    return IMPORT_NAMES.get(name, name.replace("-", "_"))


def read_script_metadata(source: str) -> ScriptMetadata | None:
    """Return the module's PEP 723 ``script`` block, if any."""
    blocks = [m for m in PEP723_RE.finditer(source) if m.group("type") == "script"]
    if not blocks:
        return None
    if len(blocks) > 1:
        raise InlineError("multiple PEP 723 script blocks")
    content = "".join(
        line[2:] if line.startswith("# ") else line[1:]
        for line in blocks[0].group("content").splitlines(keepends=True)
    )
    try:
        data = tomllib.loads(content)
    except tomllib.TOMLDecodeError as exc:
        raise InlineError(f"invalid PEP 723 script block: {exc}") from exc
    dependencies = data.get("dependencies", [])
    if not isinstance(dependencies, list) or not all(isinstance(d, str) for d in dependencies):
        raise InlineError("PEP 723 dependencies must be a list of strings")
    for dependency in dependencies:
        _import_name(dependency)
    return ScriptMetadata(block=blocks[0].group(0), dependencies=tuple(dependencies))


def _block_lines(source: str, block: str) -> tuple[int, int]:
    first = source.count("\n", 0, source.index(block)) + 1
    return first, first + block.count("\n")


def _check_nested_imports(tree: ast.Module, current_file: Path, allowed: frozenset[str]) -> None:
    # Only top-level imports are inlined; an import inside a function or block
    # would survive into the generated file unchanged.
    top_level = {id(node) for node in tree.body}
    for node in ast.walk(tree):
        if not isinstance(node, (ast.Import, ast.ImportFrom)) or id(node) in top_level:
            continue
        where = f"{current_file}:{node.lineno}"
        if isinstance(node, ast.ImportFrom) and node.level:
            raise InlineError(
                f"{where}: relative import inside a function/block cannot be inlined; "
                "move it to module top level"
            )
        for top in _import_tops(node):
            if top == "agent_tooling":
                raise InlineError(
                    f"{where}: agent_tooling import inside a function/block cannot be inlined; "
                    "move it to module top level"
                )
            if top not in STDLIB and top not in allowed:
                raise InlineError(f"{where}: import {top} is outside agent_tooling/")


def collect_graph(
    entry: Path, package_root: Path, allowed: frozenset[str] = frozenset()
) -> tuple[list[Path], dict[Path, str]]:
    entry = entry.resolve()
    sources: dict[Path, str] = {}
    deps: dict[Path, set[Path]] = {}

    def visit(path: Path) -> None:
        path = path.resolve()
        if path in sources:
            return
        text = path.read_text(encoding="utf-8")
        sources[path] = text
        if path != entry and read_script_metadata(text) is not None:
            raise InlineError(f"{path}: only the entry module may declare a PEP 723 block")
        tree = ast.parse(text)
        _check_nested_imports(tree, path, allowed)
        deps[path] = set()
        for node in tree.body:
            if not isinstance(node, (ast.Import, ast.ImportFrom)):
                continue
            for target in hook_targets(node, path, package_root, allowed):
                deps[path].add(target)
                visit(target)

    visit(entry)
    visiting: set[Path] = set()
    done: set[Path] = set()
    order: list[Path] = []

    def dfs(path: Path) -> None:
        if path in done:
            return
        if path in visiting:
            raise InlineError(f"circular import involving {path}")
        visiting.add(path)
        for dep in sorted(deps[path], key=lambda p: p.as_posix()):
            dfs(dep)
        visiting.remove(path)
        done.add(path)
        order.append(path)

    dfs(entry)
    return order, sources


def _is_hooks_import(node: ast.stmt) -> bool:
    if isinstance(node, ast.ImportFrom):
        if node.level and node.level > 0:
            return True
        top = (node.module or "").split(".")[0]
        return top == "hooks"
    if isinstance(node, ast.Import):
        return any(alias.name.split(".")[0] == "hooks" for alias in node.names)
    return False


def collect_stdlib_imports(
    order: list[Path], sources: dict[Path, str], allowed: frozenset[str] = frozenset()
) -> tuple[list[str], list[str], list[str]]:
    """Return deduplicated ``(__future__, stdlib, allowed third-party)`` import lines."""
    future: list[str] = []
    stdlib: list[str] = []
    third_party: list[str] = []
    seen: set[str] = set()
    for path in order:
        tree = ast.parse(sources[path])
        for node in tree.body:
            if not isinstance(node, (ast.Import, ast.ImportFrom)):
                continue
            if _is_hooks_import(node):
                continue
            if _is_stdlib_import(node):
                bucket = future if _is_future(node) else stdlib
            elif _is_third_party_import(node, allowed):
                bucket = third_party
            else:
                continue
            text = ast.unparse(node)
            if text not in seen:
                seen.add(text)
                bucket.append(text)
    return future, stdlib, third_party


def _defined_names(tree: ast.Module) -> set[str]:
    names: set[str] = set()
    for node in tree.body:
        if isinstance(node, (ast.FunctionDef, ast.AsyncFunctionDef, ast.ClassDef)):
            names.add(node.name)
        elif isinstance(node, ast.Assign):
            for target in node.targets:
                names.update(n.id for n in ast.walk(target) if isinstance(n, ast.Name))
        elif isinstance(node, (ast.AnnAssign, ast.AugAssign)) and isinstance(node.target, ast.Name):
            names.add(node.target.id)
    return {name for name in names if not (name.startswith("__") and name.endswith("__"))}


def _import_bindings(tree: ast.Module) -> dict[str, str]:
    """Names bound by top-level imports that survive inlining -> what they refer to."""
    bindings: dict[str, str] = {}
    for node in tree.body:
        if _is_future(node) or _is_hooks_import(node):
            continue
        if isinstance(node, ast.Import):
            for alias in node.names:
                if alias.name.split(".")[0] == "agent_tooling":
                    continue
                if alias.asname:
                    bindings[alias.asname] = alias.name
                else:
                    top = alias.name.split(".")[0]
                    bindings[top] = top
        elif isinstance(node, ast.ImportFrom):
            if (node.module or "").split(".")[0] == "agent_tooling":
                continue
            for alias in node.names:
                bindings[alias.asname or alias.name] = f"{node.module}.{alias.name}"
    return bindings


def check_name_collisions(order: list[Path], sources: dict[Path, str], package_root: Path) -> None:
    """Fail when two inlined modules bind the same top-level name differently.

    Covers definitions (functions, classes, module constants) and surviving
    imports: ``import datetime`` in one module and ``from datetime import
    datetime`` in another would silently shadow each other once flattened.
    """

    def rel(path: Path) -> str:
        return path.relative_to(package_root.resolve()).as_posix()

    owner: dict[str, tuple[Path, str]] = {}
    for path in order:
        tree = ast.parse(sources[path])
        bound = {name: f"def:{rel(path)}" for name in _defined_names(tree)}
        for name, target in _import_bindings(tree).items():
            bound.setdefault(name, f"import:{target}")
        for name in sorted(bound):
            first_path, first_kind = owner.setdefault(name, (path, bound[name]))
            if first_path == path or first_kind == bound[name]:
                continue
            what = (
                "defined"
                if first_kind.startswith("def:") and bound[name].startswith("def:")
                else "bound"
            )
            raise InlineError(
                f"top-level name {name!r} is {what} differently in {rel(first_path)} and "
                f"{rel(path)}; rename one (or import it the same way) before inlining"
            )


def render_complete(entry: Path, package_root: Path, allowed: frozenset[str] | None = None) -> str:
    """Inline ``entry``'s package imports. ``allowed`` defaults to its PEP 723 dependencies."""
    entry = entry.resolve()
    metadata = read_script_metadata(entry.read_text(encoding="utf-8"))
    if allowed is None:
        allowed = metadata.import_names if metadata else frozenset()
    order, sources = collect_graph(entry, package_root, allowed)
    check_name_collisions(order, sources, package_root)
    entry_tree = ast.parse(sources[entry])
    docstring = module_docstring_source(sources[entry], entry_tree)
    future, stdlib, third_party = collect_stdlib_imports(order, sources, allowed)

    chunks: list[str] = [SHEBANG]
    if metadata:
        chunks.append(metadata.block + "\n")
    chunks += [docstring, "\n", GENERATED_MARK, "\n"]
    if future:
        chunks.append("\n".join(future) + "\n\n")
    if stdlib:
        chunks.append("\n".join(stdlib) + "\n")
    if third_party:
        chunks.append("\n" + "\n".join(third_party) + "\n")

    for path in order:
        if path == entry:
            continue
        rel = path.resolve().relative_to(package_root.resolve()).as_posix()
        body = remaining_source(
            sources[path], ast.parse(sources[path]), skip_docstring=True, skip_main_guard=True
        )
        chunks.append(f"\n# --- inlined from {rel} ---\n")
        if body:
            chunks.append(body if body.endswith("\n") else body + "\n")

    entry_rel = entry.resolve().relative_to(package_root.resolve()).as_posix()
    entry_body = remaining_source(
        sources[entry],
        entry_tree,
        skip_docstring=True,
        skip_lines=_block_lines(sources[entry], metadata.block) if metadata else None,
    )
    chunks.append(f"\n# --- {entry_rel} ---\n")
    if entry_body:
        chunks.append(entry_body if entry_body.endswith("\n") else entry_body + "\n")
    return "".join(chunks)


def _require(condition: bool, where: Path, message: str) -> None:
    if not condition:
        raise InlineError(f"{where}: {message}")


def _check_keys(data: dict, allowed: frozenset[str], where: Path, what: str) -> None:
    unknown = sorted(set(data) - allowed)
    _require(not unknown, where, f"unknown {what} key(s): {', '.join(map(str, unknown))}")


def _relative_posix(value: object, where: Path, what: str) -> str:
    _require(isinstance(value, str) and bool(value), where, f"{what} must be a non-empty string")
    path = PurePosixPath(value)
    _require(
        "\\" not in value
        and not path.is_absolute()
        and ".." not in path.parts
        and ":" not in value,
        where,
        f"{what} must be a relative POSIX path without '..': {value!r}",
    )
    return path.as_posix()


def _string_list(value: object, where: Path, what: str) -> tuple[str, ...]:
    if value is None:
        return ()
    _require(
        isinstance(value, list) and all(isinstance(v, str) and v for v in value),
        where,
        f"{what} must be a list of strings",
    )
    return tuple(value)


def _parse_registration(agent: str, raw: object, where: Path) -> dict:
    _require(isinstance(raw, dict), where, f"agents.{agent}.registrations[] must be a mapping")
    command_keys = sorted(set(raw) & COMMAND_KEYS)
    _require(
        not command_keys,
        where,
        f"agents.{agent}.registrations[] must not contain {', '.join(command_keys)}; "
        "the installer builds the command",
    )
    _check_keys(raw, REGISTRATION_KEYS[agent], where, f"agents.{agent}.registrations[]")
    _require(
        isinstance(raw.get("event"), str) and bool(raw["event"]),
        where,
        f"agents.{agent}.registrations[].event is required",
    )
    if "matcher" in raw:
        _require(
            isinstance(raw["matcher"], str) and bool(raw["matcher"]),
            where,
            f"agents.{agent}.registrations[].matcher must be a non-empty string",
        )
    return dict(raw)


def _parse_agent(agent: str, raw: object, distributable: bool, where: Path) -> AgentSpec:
    raw = {} if raw is None else raw
    _require(isinstance(raw, dict), where, f"agents.{agent} must be a mapping")
    _check_keys(raw, AGENT_KEYS, where, f"agents.{agent}")
    runner = raw.get("runner", "python")
    _require(runner in RUNNERS, where, f"agents.{agent}.runner must be one of {', '.join(RUNNERS)}")
    _require(
        runner != "uv-project" or not distributable,
        where,
        "runner uv-project needs this repository's uv project; set distributable: false",
    )
    project_imports = _string_list(raw.get("project_imports"), where, "project_imports")
    _require(
        not project_imports or runner == "uv-project",
        where,
        f"agents.{agent}.project_imports is only valid with runner uv-project",
    )
    registrations_raw = raw.get("registrations") or []
    _require(
        isinstance(registrations_raw, list), where, f"agents.{agent}.registrations must be a list"
    )
    if agent == "kilo":
        _require(not registrations_raw, where, "kilo has no registrations (placement enables it)")
    else:
        _require(bool(registrations_raw), where, f"agents.{agent}.registrations is required")
    seeds_raw = raw.get("seed_files") or []
    _require(isinstance(seeds_raw, list), where, f"agents.{agent}.seed_files must be a list")
    seeds: list[SeedFile] = []
    for seed in seeds_raw:
        _require(isinstance(seed, dict), where, f"agents.{agent}.seed_files[] must be a mapping")
        _check_keys(seed, SEED_KEYS, where, f"agents.{agent}.seed_files[]")
        seeds.append(
            SeedFile(
                source=_relative_posix(seed.get("source"), where, "seed_files[].source"),
                path=_relative_posix(seed.get("path"), where, "seed_files[].path"),
            )
        )
    _require(len({s.path for s in seeds}) == len(seeds), where, "duplicate seed_files[].path")
    return AgentSpec(
        runner=runner,
        registrations=tuple(_parse_registration(agent, r, where) for r in registrations_raw),
        seed_files=tuple(seeds),
        project_imports=project_imports,
    )


def load_hook_spec(path: Path) -> HookSpec:
    """Parse and validate one ``scenarios/<id>/hook.yaml``."""
    try:
        data = yaml.safe_load(path.read_text(encoding="utf-8"))
    except yaml.YAMLError as exc:
        raise InlineError(f"{path}: invalid YAML: {exc}") from exc
    _require(isinstance(data, dict), path, "hook.yaml must be a mapping")
    _check_keys(data, HOOK_KEYS, path, "hook.yaml")
    hook_id = data.get("id")
    _require(
        hook_id == path.parent.name, path, f"id must equal the directory name {path.parent.name!r}"
    )
    description = data.get("description")
    _require(
        isinstance(description, str)
        and bool(description.strip())
        and "\n" not in description.strip(),
        path,
        "description must be a one-line string",
    )
    distributable = data.get("distributable", True)
    _require(isinstance(distributable, bool), path, "distributable must be a boolean")
    agents_raw = data.get("agents")
    _require(
        isinstance(agents_raw, dict) and bool(agents_raw),
        path,
        "agents must be a non-empty mapping",
    )
    unknown = sorted(set(agents_raw) - set(AGENTS))
    _require(not unknown, path, f"unknown agent(s): {', '.join(map(str, unknown))}")
    agents = {
        agent: _parse_agent(agent, agents_raw[agent], distributable, path)
        for agent in AGENTS
        if agent in agents_raw
    }
    return HookSpec(
        id=hook_id,
        description=description.strip(),
        distributable=distributable,
        requires_tools=_string_list(data.get("requires_tools"), path, "requires_tools"),
        agents=agents,
        directory=path.parent,
    )


def load_hook_specs(package_root: Path) -> dict[str, HookSpec]:
    scenarios = package_root / SCENARIOS_DIR
    paths = sorted(scenarios.glob("*/hook.yaml")) if scenarios.is_dir() else []
    return {spec.id: spec for spec in map(load_hook_spec, paths)}


def _repo_tool_keys(package_root: Path) -> set[str] | None:
    path = package_root.parent.parent / "repo-tools.yaml"
    if not path.is_file():
        return None
    data = yaml.safe_load(path.read_text(encoding="utf-8")) or {}
    return set((data.get("tools") or {}).keys())


def validate_specs(
    specs: dict[str, HookSpec], entries: tuple[Entry, ...], package_root: Path
) -> dict[tuple[str, str], ScriptMetadata | None]:
    """Cross-check hook.yaml against ENTRIES; return each entry's PEP 723 metadata."""
    by_hook: dict[str, set[str]] = {}
    for entry in entries:
        agent, hook_id = entry.key
        if agent not in AGENTS or not hook_id:
            raise InlineError(f"ENTRIES name must be '<agent>:<hook id>': {entry.name}")
        by_hook.setdefault(hook_id, set()).add(agent)
    missing_yaml = sorted(set(by_hook) - set(specs))
    if missing_yaml:
        raise InlineError(
            f"ENTRIES has no {SCENARIOS_DIR}/<id>/hook.yaml for: {', '.join(missing_yaml)}"
        )
    missing_entries = sorted(set(specs) - set(by_hook))
    if missing_entries:
        raise InlineError(f"hook.yaml without ENTRIES: {', '.join(missing_entries)}")
    for hook_id, spec in specs.items():
        if set(spec.agents) != by_hook[hook_id]:
            raise InlineError(
                f"{hook_id}: hook.yaml agents {sorted(spec.agents)} != "
                f"ENTRIES agents {sorted(by_hook[hook_id])}"
            )
        for agent, agent_spec in spec.agents.items():
            for seed in agent_spec.seed_files:
                if not (spec.directory / seed.source).is_file():
                    raise InlineError(f"{hook_id}: missing seed source {seed.source}")
    tool_keys = _repo_tool_keys(package_root)
    if tool_keys is not None:
        for spec in specs.values():
            unknown = sorted(set(spec.requires_tools) - tool_keys)
            if unknown:
                raise InlineError(
                    f"{spec.id}: requires_tools not in repo-tools.yaml: {', '.join(unknown)}"
                )
    metadata: dict[tuple[str, str], ScriptMetadata | None] = {}
    for entry in entries:
        agent, hook_id = entry.key
        runner = specs[hook_id].agents[agent].runner
        source = package_root / entry.source
        if not source.is_file():
            raise InlineError(f"missing entry source: {source}")
        meta = read_script_metadata(source.read_text(encoding="utf-8"))
        if (meta is not None) != (runner == "uv-script"):
            raise InlineError(
                f"{entry.name}: runner {runner} "
                + ("must not have" if meta else "requires")
                + " a PEP 723 script block in the entry module"
            )
        metadata[entry.key] = meta
    return metadata


def _allowed_imports(spec: AgentSpec, meta: ScriptMetadata | None) -> frozenset[str]:
    if meta is not None:
        return meta.import_names
    return frozenset(spec.project_imports)


def _generated_rel(output: str) -> str:
    return PurePosixPath(output).relative_to(GENERATED_DIR).as_posix()


def seed_outputs(specs: dict[str, HookSpec]) -> list[tuple[Path, str]]:
    """``(source file, package-relative destination)`` for every seed file."""
    return [
        (spec.directory / seed.source, f"{GENERATED_DIR}/{agent}/seed/{spec.id}/{seed.path}")
        for spec in specs.values()
        for agent, agent_spec in spec.agents.items()
        for seed in agent_spec.seed_files
    ]


def render_catalog(
    specs: dict[str, HookSpec],
    entries: tuple[Entry, ...],
    metadata: dict[tuple[str, str], ScriptMetadata | None],
) -> str:
    """Render generated/catalog.json. Paths are relative to the catalog's directory."""
    by_key = {entry.key: entry for entry in entries}
    hooks = []
    for hook_id in sorted(specs):
        spec = specs[hook_id]
        agents = {}
        for agent, agent_spec in spec.agents.items():
            entry = by_key[(agent, hook_id)]
            outputs = [entry.output, *(dest for _, dest in entry.copies)]
            files = [
                {"path": _generated_rel(out), "installPath": PurePosixPath(out).name}
                for out in outputs
            ]
            if agent == "kilo":
                main = next((f for f in files if f["installPath"].endswith(".ts")), None)
                if main is None:
                    raise InlineError(f"{entry.name}: kilo needs a .ts plugin in copies")
            else:
                main = files[0]
            meta = metadata[entry.key]
            agents[agent] = {
                "runner": agent_spec.runner,
                "main": main["installPath"],
                "files": files,
                "seedFiles": [
                    {
                        "path": f"{agent}/seed/{hook_id}/{seed.path}",
                        "installPath": seed.path,
                    }
                    for seed in agent_spec.seed_files
                ],
                "dependencies": list(meta.dependencies) if meta else [],
                "registrations": list(agent_spec.registrations),
            }
        hooks.append(
            {
                "id": hook_id,
                "description": spec.description,
                "distributable": spec.distributable,
                "requiresTools": list(spec.requires_tools),
                "agents": agents,
            }
        )
    catalog = {
        "schemaVersion": CATALOG_SCHEMA_VERSION,
        "generatedBy": "agent-tooling/agent_tooling/hooks/build/build.py",
        "hooks": hooks,
    }
    return json.dumps(catalog, ensure_ascii=False, indent=2) + "\n"


def format_with_ruff(*paths: Path) -> None:
    # One ruff process for every file: spawning `uv run ruff` per file dominated build time.
    if not paths:
        return
    targets = [str(path) for path in paths]
    for argv in (
        ["uv", "run", "ruff", "format", *targets],
        ["ruff", "format", *targets],
    ):
        try:
            result = subprocess.run(argv, check=False, capture_output=True)
        except OSError:
            continue
        if result.returncode == 0:
            return


def write_unformatted(text: str, output: Path) -> None:
    output.parent.mkdir(parents=True, exist_ok=True)
    output.write_text(text, encoding="utf-8", newline="\n")


def write_complete(text: str, output: Path) -> None:
    write_unformatted(text, output)
    format_with_ruff(output)


def copy_sidecars(entry: Entry, package_root: Path, *, check: bool = False) -> list[Path]:
    written: list[Path] = []
    for src_rel, dest_rel in entry.copies:
        src = (package_root / src_rel).resolve()
        dest = (package_root / dest_rel).resolve()
        if not src.is_file():
            raise InlineError(f"missing sidecar: {src}")
        text = src.read_text(encoding="utf-8")
        dest_rel_posix = Path(dest_rel).as_posix()
        if check:
            if not dest.is_file():
                raise InlineError(f"missing complete file: {dest}")
            if dest.read_text(encoding="utf-8") != text:
                raise InlineError(f"complete drift: {dest_rel_posix}")
        else:
            dest.parent.mkdir(parents=True, exist_ok=True)
            dest.write_text(text, encoding="utf-8", newline="\n")
        written.append(dest)
    return written


def _write_or_check_bytes(data: bytes, dest: Path, rel: str, *, check: bool) -> Path:
    if check:
        if not dest.is_file():
            raise InlineError(f"missing generated file: {rel}")
        if dest.read_bytes() != data:
            raise InlineError(f"complete drift: {rel}")
    else:
        dest.parent.mkdir(parents=True, exist_ok=True)
        dest.write_bytes(data)
    return dest


def build_entry(entry: Entry, hooks_root: Path | None = None) -> Path:
    root = hooks_root or PACKAGE_ROOT
    source = (root / entry.source).resolve()
    output = (root / entry.output).resolve()
    if not source.is_file():
        raise InlineError(f"missing entry source: {source}")
    write_complete(render_complete(source, root), output)
    copy_sidecars(entry, root, check=False)
    return output


def assert_complete_contract(text: str) -> None:
    if not text.startswith("#!/usr/bin/env python3\n"):
        raise InlineError("complete file must start with python3 shebang")
    rest = text.split("\n", 1)[1]
    stripped = rest.lstrip("\n")
    if stripped.startswith("# /// script\n"):
        end = stripped.find("\n# ///\n")
        if end < 0:
            raise InlineError("unterminated PEP 723 block after shebang")
        stripped = stripped[end + len("\n# ///\n") :].lstrip("\n")
    if not stripped.startswith('"""') and not stripped.startswith("'''"):
        raise InlineError(
            "shebang (then an optional PEP 723 block) must be followed by the entry docstring"
        )
    tree = ast.parse(text)
    for node in ast.walk(tree):
        if isinstance(node, ast.ImportFrom) and node.level and node.level > 0:
            raise InlineError("relative import left in complete file")
        if isinstance(node, ast.ImportFrom) and (node.module or "").split(".")[:1] == [
            "agent_tooling"
        ]:
            raise InlineError("agent_tooling.* import left in complete file")
        if isinstance(node, ast.Import):
            for alias in node.names:
                if alias.name.split(".")[0] == "agent_tooling":
                    raise InlineError("agent_tooling import left in complete file")


def build_all(
    *,
    check: bool = False,
    hooks_root: Path | None = None,
    entries: tuple[Entry, ...] | None = None,
) -> list[Path]:
    root = hooks_root or PACKAGE_ROOT
    entries = ENTRIES if entries is None else entries
    specs = load_hook_specs(root)
    metadata = validate_specs(specs, entries, root)
    seeds = seed_outputs(specs)
    written: list[Path] = []
    manifest = {Path(entry.output).as_posix() for entry in entries}
    manifest.update(
        Path(destination).as_posix() for entry in entries for _, destination in entry.copies
    )
    manifest.update(dest for _, dest in seeds)
    manifest.add(CATALOG_OUTPUT)
    generated_root = root / GENERATED_DIR
    actual = (
        {
            path.relative_to(root).as_posix()
            for path in generated_root.rglob("*")
            if path.is_file() and path.name != "README.md" and "__pycache__" not in path.parts
        }
        if generated_root.is_dir()
        else set()
    )
    stale = sorted(actual - manifest)
    if stale:
        if check:
            raise InlineError(f"stale generated file: {stale[0]}")
        for relative in stale:
            (root / relative).unlink()
    outputs: list[Path] = []
    for entry in entries:
        agent, hook_id = entry.key
        source = (root / entry.source).resolve()
        output = (root / entry.output).resolve()
        allowed = _allowed_imports(specs[hook_id].agents[agent], metadata[entry.key])
        text = render_complete(source, root, allowed)
        assert_complete_contract(text)
        if check and not output.is_file():
            raise InlineError(f"missing generated file: {output}")
        write_unformatted(text, _checktmp(output) if check else output)
        outputs.append(output)
        written.append(output)
        written.extend(copy_sidecars(entry, root, check=check))
    for source, dest in seeds:
        written.append(_write_or_check_bytes(source.read_bytes(), root / dest, dest, check=check))
    catalog = render_catalog(specs, entries, metadata).encode("utf-8")
    written.append(
        _write_or_check_bytes(catalog, root / CATALOG_OUTPUT, CATALOG_OUTPUT, check=check)
    )
    if check:
        tmps = [_checktmp(output) for output in outputs]
        try:
            format_with_ruff(*tmps)
            for output, tmp in zip(outputs, tmps, strict=True):
                if tmp.read_text(encoding="utf-8") != output.read_text(encoding="utf-8"):
                    raise InlineError(f"complete drift: {output.relative_to(root).as_posix()}")
        finally:
            for tmp in tmps:
                tmp.unlink(missing_ok=True)
    else:
        format_with_ruff(*outputs)
        for output in outputs:
            assert_complete_contract(output.read_text(encoding="utf-8"))
    return written


def _checktmp(output: Path) -> Path:
    return output.with_suffix(output.suffix + ".checktmp")


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "--check",
        action="store_true",
        help="fail if agent_tooling/hooks/generated/ does not match a fresh build",
    )
    args = parser.parse_args(argv)
    try:
        build_all(check=args.check)
    except InlineError as exc:
        print(f"error: {exc}", file=sys.stderr)
        return 1
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
